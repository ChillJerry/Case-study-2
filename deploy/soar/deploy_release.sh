
#!/usr/bin/env bash
set -Eeuo pipefail

BASE="/opt/innovatech/soar"
APP_DIR="$BASE/repo"
VENV="$BASE/venv"
SERVICE="innovatech-soar.service"
HEALTH_URL="http://10.20.20.10:8000/health"

ARTIFACT="${1:?Usage: deploy_release.sh s3_uri sha256}"
EXPECTED_SHA="${2:?Missing artifact SHA256}"

BACKUP=""
VENV_BACKUP=""
VENV_STAGING=""
STAGING=""
ARCHIVE=""
DEPENDENCIES_CHANGED=0

cleanup() {
    if [[ -n "$STAGING" && -d "$STAGING" ]]; then
        rm -rf -- "$STAGING"
    fi

    if [[ -n "$ARCHIVE" && -f "$ARCHIVE" ]]; then
        rm -f -- "$ARCHIVE"
    fi

    if [[ -n "$VENV_STAGING" && -d "$VENV_STAGING" ]]; then
        rm -rf -- "$VENV_STAGING"
    fi
}

rollback() {
    local exit_code=$?
    trap - ERR
    set +e

    echo "Deployment failed (exit code $exit_code)."
    echo "Attempting rollback..."

    # Restore the previous Python environment first.
    if [[ -n "$VENV_BACKUP" && -d "$VENV_BACKUP" ]]; then
        if [[ -d "$VENV" ]]; then
            mv "$VENV" "$BASE/failed-venv-$(date +%s)-$$"
        fi

        mv "$VENV_BACKUP" "$VENV"
        echo "Previous Python environment restored."
    fi

    # Restore the previous application release.
    if [[ -n "$BACKUP" && -d "$BACKUP" ]]; then
        if [[ -d "$APP_DIR" ]]; then
            mv "$APP_DIR" "$BASE/failed-release-$(date +%s)-$$"
        fi

        mv "$BACKUP" "$APP_DIR"
        echo "Previous SOAR release restored."
    fi

    if [[ -d "$APP_DIR" && -x "$VENV/bin/python" ]]; then
        systemctl restart "$SERVICE" || true
    fi

    cleanup
    exit "$exit_code"
}

trap rollback ERR
trap cleanup EXIT

if [[ "$(id -u)" -ne 0 ]]; then
    echo "This script must run as root."
    exit 1
fi

if [[ ! -d "$APP_DIR/app/soar" ]]; then
    echo "Existing SOAR installation not found."
    exit 1
fi

if [[ ! -x "$VENV/bin/python" ]]; then
    echo "SOAR virtual environment not found."
    exit 1
fi

echo "Downloading SOAR release..."

STAGING="$(mktemp -d "$BASE/.staging-XXXXXXXX")"
ARCHIVE="$(mktemp /tmp/innovatech-soar-XXXXXXXX.zip)"

aws s3 cp "$ARTIFACT" "$ARCHIVE" \
    --region eu-central-1

echo "$EXPECTED_SHA  $ARCHIVE" | sha256sum -c -

unzip -q "$ARCHIVE" -d "$STAGING"

echo "Validating release files..."

for file in \
    app/soar/__init__.py \
    app/soar/main.py \
    app/soar/rules.py \
    app/soar/actions.py \
    app/soar/postgres_store.py \
    app/soar/dedup.py \
    app/soar/metrics.py \
    app/soar/requirements.txt
do
    if [[ ! -f "$STAGING/$file" ]]; then
        echo "Missing required release file: $file"
        exit 1
    fi
done

if [[ ! -d "$STAGING/app/soar/playbooks" ]]; then
    echo "Missing SOAR playbooks."
    exit 1
fi

python3 -m compileall -q "$STAGING/app/soar"
chmod -R a+rX "$STAGING"

echo "Checking Python dependencies..."

if ! cmp -s \
    "$APP_DIR/app/soar/requirements.txt" \
    "$STAGING/app/soar/requirements.txt" \
    || ! "$VENV/bin/python" -c "import psycopg" 2>/dev/null
then
    DEPENDENCIES_CHANGED=1
    echo "Installing dependencies into a staged environment..."

    # Copy the working environment so failed updates
    # cannot modify the currently running environment.
    VENV_STAGING="$BASE/.venv-staging-$(date +%s)-$$"
    cp -a "$VENV" "$VENV_STAGING"

    "$VENV_STAGING/bin/python" -m pip install \
        --disable-pip-version-check \
        --no-input \
        -r "$STAGING/app/soar/requirements.txt"

    "$VENV_STAGING/bin/python" -c "import psycopg"

    # Console scripts generated by pip can contain the
    # temporary virtual environment path in their shebang.
    # Replace it with the permanent deployment path.
    python3 - "$VENV_STAGING" "$VENV" <<'PY'
import sys
from pathlib import Path

temporary = sys.argv[1].encode()
permanent = sys.argv[2].encode()
bin_dir = Path(sys.argv[1]) / "bin"

for path in bin_dir.iterdir():
    if not path.is_file() or path.is_symlink():
        continue

    with path.open("rb") as handle:
        first_line = handle.readline()

    if not first_line.startswith(b"#!"):
        continue

    if temporary not in first_line:
        continue

    content = path.read_bytes()
    first, separator, remaining = content.partition(b"\n")

    path.write_bytes(
        first.replace(temporary, permanent)
        + separator
        + remaining
    )
PY

    echo "Staged Python dependencies verified."
else
    echo "Existing Python dependencies are sufficient."
fi

# Verify that the new application can import its modules.
echo "Checking SOAR application imports..."

if [[ "$DEPENDENCIES_CHANGED" -eq 1 ]]; then
    CHECK_PYTHON="$VENV_STAGING/bin/python"
else
    CHECK_PYTHON="$VENV/bin/python"
fi

PYTHONPATH="$STAGING" "$CHECK_PYTHON" -c \
    "import app.soar.main; import app.soar.postgres_store"

echo "Creating release backup..."

BACKUP="$BASE/repo.backup-$(date +%Y%m%d-%H%M%S)-$$"
mv "$APP_DIR" "$BACKUP"

# Only switch environments when dependencies changed.
if [[ "$DEPENDENCIES_CHANGED" -eq 1 ]]; then
    echo "Backing up current Python environment..."

    VENV_BACKUP="$BASE/venv.backup-$(date +%Y%m%d-%H%M%S)-$$"
    mv "$VENV" "$VENV_BACKUP"

    echo "Activating updated Python environment..."
    mv "$VENV_STAGING" "$VENV"
    VENV_STAGING=""
fi

echo "Installing new SOAR release..."

mv "$STAGING" "$APP_DIR"
STAGING=""

systemctl restart "$SERVICE"

echo "Checking SOAR health..."

HEALTHY=0

for attempt in {1..10}; do
    if curl -fsS --max-time 5 "$HEALTH_URL" |
        python3 -c '
import json
import sys

data = json.load(sys.stdin)
sys.exit(
    0 if data.get("status") == "healthy" else 1
)
'
    then
        HEALTHY=1
        break
    fi

    sleep 2
done

if [[ "$HEALTHY" -ne 1 ]]; then
    echo "SOAR health verification failed."
    false
fi

echo "SOAR deployment successful."
echo "Previous release retained at: $BACKUP"
echo "Health endpoint: $HEALTH_URL"

if [[ "$DEPENDENCIES_CHANGED" -eq 1 ]]; then
    echo "Previous Python environment retained at: $VENV_BACKUP"
fi
